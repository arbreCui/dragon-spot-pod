      SUBROUTINE FLUSP64(JPSYS,NPSYS,IPTRK,IMPX,NGRP,NMAT,NREG,NUN,
     1 MAT,VOL,KEYFLX,TITR,ILEAK,B2,NMERG,IMERG,DIFHET,FLUOLD,SUN,FUN)
*
*  REAL64 SPOT-door dispatch for FLU2DR64: applies the SIGS (ILEAK=3)
*  leakage source correction in double precision and calls SPOF64.
*
      USE GANLIB
      TYPE(C_PTR) JPSYS,IPTRK
      INTEGER NPSYS(NGRP),IMPX,NGRP,NMAT,NREG,NUN,MAT(NREG),
     1 KEYFLX(NREG),ILEAK,NMERG,IMERG(NMAT)
      REAL VOL(NREG),B2(4),DIFHET(NMERG,NGRP)
      CHARACTER TITR*72
      DOUBLE PRECISION FLUOLD(NUN,NGRP),SUN(NUN,NGRP),FUN(NUN,NGRP)
      TYPE(C_PTR), ALLOCATABLE, DIMENSION(:) :: KPSYS
      INTEGER, ALLOCATABLE, DIMENSION(:) :: NGIND
      DOUBLE PRECISION, ALLOCATABLE, DIMENSION(:,:) :: F2,S2
      INTEGER IG,JJ,NGEFF,IR,IND,IBM,INM,IGFIRST,IGLAST
      LOGICAL DIRECT_OUTPUT_WINDOW
*  An explicit interface permits scalar array-element sequence association
*  to the original contiguous NUN by NGEFF receiver, without a section copy.
      INTERFACE
        SUBROUTINE SPOF64(KPSYS,IPTRK,IMPX,NGEFF,NGIND,NREG,NMAT,NUN,
     1   MAT,KEYFLX,FUNKNO,SUNKNO,TITR)
          USE GANLIB
          INTEGER NGEFF,NGIND(NGEFF),IMPX,NREG,NMAT,NUN,MAT(NREG),
     1     KEYFLX(NREG)
          TYPE(C_PTR) KPSYS(NGEFF),IPTRK
          DOUBLE PRECISION FUNKNO(NUN,NGEFF),SUNKNO(NUN,NGEFF)
          CHARACTER TITR*72
        END SUBROUTINE SPOF64
      END INTERFACE
      IF((ILEAK.NE.0).AND.(ILEAK.NE.3))
     1 CALL XABORT('FLUSP64: UNSUPPORTED LEAKAGE MODEL.')
      NGEFF=0
      IGFIRST=0
      IGLAST=0
      DO IG=1,NGRP
        IF(NPSYS(IG).NE.0) THEN
          NGEFF=NGEFF+1
          IF(IGFIRST.EQ.0) IGFIRST=IG
          IGLAST=IG
        ENDIF
      ENDDO
      IF(NGEFF.EQ.0) RETURN
      DIRECT_OUTPUT_WINDOW=(IGLAST-IGFIRST+1.EQ.NGEFF)
      ALLOCATE(KPSYS(NGEFF),NGIND(NGEFF),S2(NUN,NGEFF))
      IF(.NOT.DIRECT_OUTPUT_WINDOW) ALLOCATE(F2(NUN,NGEFF))
      JJ=0
      DO IG=1,NGRP
        IF(NPSYS(IG).NE.0) THEN
          JJ=JJ+1
          NGIND(JJ)=IG
          KPSYS(JJ)=LCMGIL(JPSYS,NPSYS(IG))
          S2(:NUN,JJ)=SUN(:NUN,IG)
          IF(.NOT.DIRECT_OUTPUT_WINDOW) THEN
            F2(:NUN,JJ)=FUN(:NUN,IG)
          ENDIF
          IF((ILEAK.EQ.3).AND.(B2(4).NE.0.0)) THEN
            DO IR=1,NREG
              IND=KEYFLX(IR)
              IF(IND.EQ.0) GO TO 10
              IBM=MAT(IR)
              IF(IBM.EQ.0) GO TO 10
              INM=IMERG(IBM)
              IF(INM.EQ.0) GO TO 10
              S2(IND,JJ)=S2(IND,JJ)-DBLE(DIFHET(INM,IG))*DBLE(B2(4))*
     1        FLUOLD(IND,IG)
   10         CONTINUE
            ENDDO
          ENDIF
        ENDIF
      ENDDO
      IF(DIRECT_OUTPUT_WINDOW) THEN
        CALL SPOF64(KPSYS,IPTRK,IMPX,NGEFF,NGIND,NREG,NMAT,NUN,MAT,
     1   KEYFLX,FUN(1,NGIND(1)),S2,TITR)
      ELSE
        CALL SPOF64(KPSYS,IPTRK,IMPX,NGEFF,NGIND,NREG,NMAT,NUN,MAT,
     1   KEYFLX,F2,S2,TITR)
        DO JJ=1,NGEFF
          FUN(:NUN,NGIND(JJ))=F2(:NUN,JJ)
        ENDDO
      ENDIF
      IF(ALLOCATED(F2)) DEALLOCATE(F2)
      DEALLOCATE(S2,NGIND,KPSYS)
      RETURN
      END
