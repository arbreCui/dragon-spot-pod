     > ' REBALANCING OPTION          = ',A3/
     > ' SELF-SCATTERING REDUCTION   = ',A3/
     > ' FUNDAMENTAL MODE            = ',A3/
     > ' EIGENVALUE TOLERANCE        = ',1P,E10.3/
     > ' UNKNOWN OUTER TOLERANCE     = ',E10.3/
