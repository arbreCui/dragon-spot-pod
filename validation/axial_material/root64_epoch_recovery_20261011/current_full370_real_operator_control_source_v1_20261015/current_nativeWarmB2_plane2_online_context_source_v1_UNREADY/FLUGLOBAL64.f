*DECK FLUGLOBAL64
      SUBROUTINE FLUGLOBAL64(NENTRY,HENTRY,IENTRY,JENTRY,KENTRY)
*
*-----------------------------------------------------------------------
*
*Purpose:
* Multigroup flux solution in a lattice.
*
*Copyright:
* Copyright (C) 2002 Ecole Polytechnique de Montreal
* This library is free software; you can redistribute it and/or
* modify it under the terms of the GNU Lesser General Public
* License as published by the Free Software Foundation; either
* version 2.1 of the License, or (at your option) any later version
*
*Author(s): A. Hebert
*
*Parameters: input/output
* NENTRY  number of LCM objects or files used by the operator.
* HENTRY  name of each LCM object or file.
*         HENTRY(1) create or modification type(L_FLUX).
*         HENTRY(I) for I>1:
*         read-only type(L_MACROLIB or L_LIBRARY);
*         read-only type(L_TRACK);
*         read-only sequential binary tracking file;
*         read-only type(L_PIJ);
*         optional read-only type(L_FLUX) for unperturbed solution;
*         optional read-only type(L_SOURCE) for fixed sources.
* IENTRY  type of each LCM object or file:
*         =1 LCM memory object; =2 XSM file; =3 sequential binary file;
*         =4 sequential ascii file.
* JENTRY  access of each LCM object or file:
*         =0 the LCM object or file is created;
*         =1 the LCM object or file is open for modifications;
*         =2 the LCM object or file is open in read-only mode.
* KENTRY  LCM object address or file unit number.
*
*-----------------------------------------------------------------------
*
      USE GANLIB
      USE SPOT_GLOBAL_CALLER_API, ONLY: FLUDRVG64
      USE SPOR64_BOOT_CANONICAL64_V2, ONLY:
     1 SPOR64_BOOT_CANONICAL64_WRITE
      USE SPOR64_BOOT_PUBLISH64, ONLY: SPOR64_BOOT_GLOBAL_PUBLISH,
     1 SPOR64_BOOT_GLOBAL_PUBLISHED
      USE ISO_FORTRAN_ENV, ONLY: INT64
      USE SPOR64_RCONTRACT, ONLY: SPOR64_ROUTE_CONTRACT,
     1 SPOR64_RCONTRACT_LOAD
      USE SPOR64_B2B, ONLY: SPOR64_B2B_INGRESS,
     1 SPOR64_B2B_ADMISSION_FAILED,SPOR64_B2B_CORE_FAILED,
     2 SPOR64_B2B_NOT_ACCEPTED,SPOR64_B2B_ACCEPTED_UNPUBLISHED
      USE SPOR64_B2C, ONLY: SPOR64_B2C_PREFLIGHT_FAILED,
     1 SPOR64_B2C_CHILD_PUBLISHED,SPOR64_B2C_DRIVER_COMMITTED,
     2 SPOR64_B2C_HOST_COMMITTED
*----
*  SUBROUTINE ARGUMENTS
*----
      INTEGER      NENTRY,IENTRY(NENTRY),JENTRY(NENTRY)
      TYPE(C_PTR)  KENTRY(NENTRY)
      CHARACTER    HENTRY(NENTRY)*12
*----
*  LOCAL VARIABLES
*----
      PARAMETER(IOUT=6,NSTATE=40,NLEAK=7,NSDIR=6)
      TYPE(C_PTR) IPFLUX,IPTRK,IPMACR,IPSYS,IPFLUP,IPSOU
      TYPE(C_PTR) IPRCON
      TYPE(SPOR64_ROUTE_CONTRACT) RCON
      LOGICAL LRCON
      CHARACTER TEXT12*12,TITLE*72,CMODUL*12,HSIGN*12,COPTIO*4,
     1 CXDOOR*12,TYPE10*10,HISO10*10,CREBAL*3,CHLEAK*3,HTYPE(0:5)*8,
     2 CLEAK(NLEAK)*6,CSDIR(NSDIR)*1,HPTRK*12,HPMACR*12,HPSYS*12,
     3 HPFLUP*12,HPGPT*12,HSMG*131,REDUC(4)*3
      LOGICAL LTABLE,REC,LEAKSW,LFORW,LIMERG,LR64
      DOUBLE PRECISION REFKEF
      INTEGER ISTATE(NSTATE),IMCAUD,IR64MD,IB2STAT
      INTEGER(INT64) CUTOFF64
      DOUBLE PRECISION B2(4),TERMINAL_KEFF64,TERMINAL_RESID64(3)
      DOUBLE PRECISION, ALLOCATABLE :: TERMINAL_FLUX64(:,:),
     1 TERMINAL_SOURCE64(:,:)
      INTEGER TERMINAL_COUNTERS(2),TERMINAL_INNER_STATE,IGLOBAL_STAT
      INTEGER IGLOBAL_LEN
      TYPE(C_PTR) IPGLOBAL,IPARCH_BOOT
      LOGICAL TERMINAL_VALID,CANONICAL_OK,GLOBAL_EMPTY,GLOBAL_LCM
      CHARACTER GLOBAL_NAME*72,GLOBAL_DIRECTORY*12
*----
*  ALLOCATABLE ARRAYS
*----
      INTEGER, ALLOCATABLE, DIMENSION(:) :: MATCOD,IMERG
      INTEGER, ALLOCATABLE, DIMENSION(:,:,:) :: KEYFLX
      REAL, ALLOCATABLE, DIMENSION(:) :: VOL,LEAK1D
*----
*  DATA STATEMENTS
*----
      SAVE        HTYPE,CLEAK,CSDIR
      DATA       (HTYPE(JJ),JJ=0,5)/'  SOURCE','     GPT','   K-INF',
     >            '   K-EFF','BUCKLING',' LEAKAGE'/
      DATA       (CLEAK(JJ),JJ=1,NLEAK)
     >           /'PNLR',' PNL','SIGS','ALBS','HETE','ECCO','TIBERE'/
      DATA       (CSDIR(III),III=1,NSDIR)
     >           /'-','X','Y','Z','R','G'/
      DATA       (REDUC(JJ),JJ=1,4)
     >           /'ON ','OFF','ON ','OFF'/
*----
*  PARAMETER VALIDATION.
*----
*     AX_CURRENT, GLOBAL_NEW, MACROLIB3, TRACK_AX, SYSTEM_NEXT,
*     ARCH_BOOT, RCONTRACT. GLOBAL_NEW is separate and fresh.
      TERMINAL_VALID=.FALSE.
      IPARCH_BOOT=C_NULL_PTR
      IF(NENTRY.NE.7) CALL XABORT(
     1 "FLUGLOBAL64: EXACT SEVEN OPERANDS REQUIRED.")
      IF((IENTRY(2).NE.1.AND.IENTRY(2).NE.2).OR.
     1 JENTRY(2).NE.0.OR..NOT.C_ASSOCIATED(KENTRY(2)))
     2 CALL XABORT("FLUGLOBAL64: FRESH GLOBAL OUTPUT REQUIRED.")
      IPGLOBAL=KENTRY(2)
      DO I1=1,NENTRY
        IF(I1.EQ.2) CYCLE
        IF(C_ASSOCIATED(IPGLOBAL,KENTRY(I1))) CALL XABORT(
     1   "FLUGLOBAL64: INDEPENDENT GLOBAL OBJECT REQUIRED.")
      ENDDO
      CALL LCMINF(IPGLOBAL,GLOBAL_NAME,GLOBAL_DIRECTORY,
     1 GLOBAL_EMPTY,IGLOBAL_LEN,GLOBAL_LCM)
      IF(.NOT.GLOBAL_EMPTY.OR.IGLOBAL_LEN.NE.-1.OR.
     1 TRIM(GLOBAL_DIRECTORY).NE."/") CALL XABORT(
     2 "FLUGLOBAL64: EMPTY GLOBAL ROOT DIRECTORY REQUIRED.")
      IF(ANY(JENTRY(3:7).NE.2)) CALL XABORT(
     1 "FLUGLOBAL64: FIVE COMPLETE READONLY INPUTS REQUIRED.")
      DO I1=3,7
        IF(IENTRY(I1).NE.1.AND.IENTRY(I1).NE.2)
     1   CALL XABORT("FLUGLOBAL64: READONLY LCM/XSM REQUIRED.")
      ENDDO
      IF(NENTRY.LE.1) THEN
         CALL XABORT('FLU: TWO PARAMETERS EXPECTED.')
         RETURN
      ENDIF
      IF(.NOT.C_ASSOCIATED(KENTRY(1))) THEN
         CALL XABORT('FLU: NULL PRIMARY LCM HANDLE.')
         RETURN
      ENDIF
      IF((IENTRY(1).NE.1).AND.(IENTRY(1).NE.2)) THEN
         CALL XABORT('FLU: INVALID PRIMARY LCM OBJECT TYPE.')
         RETURN
      ENDIF
      IF((JENTRY(1).NE.0).AND.(JENTRY(1).NE.1)) THEN
         CALL XABORT('FLU: PRIMARY LCM MUST BE CREATED OR MODIFIED.')
         RETURN
      ENDIF
      IPFLUX=KENTRY(1)
      REC=(JENTRY(1).EQ.1)
      IF(REC) THEN
         CALL LCMLEN(IPFLUX,'SIGNATURE',ILONG,ITYLCM)
         IF((ILONG.NE.3).OR.(ITYLCM.NE.3)) THEN
            CALL XABORT('FLU: INVALID L_FLUX SIGNATURE RECORD.')
            RETURN
         ENDIF
         CALL LCMGTC(IPFLUX,'SIGNATURE',12,HSIGN)
         IF(HSIGN.NE.'L_FLUX') THEN
            TEXT12=HENTRY(1)
            CALL XABORT('FLU: SIGNATURE OF '//TEXT12//' IS '//HSIGN//
     1      '. L_FLUX EXPECTED.')
            RETURN
         ENDIF
      ELSE
         HSIGN='L_FLUX'
      ENDIF
      IFTRAK=0
      IPMACR=C_NULL_PTR
      IPTRK=C_NULL_PTR
      IPSYS=C_NULL_PTR
      IPSOU=C_NULL_PTR
      IPFLUP=C_NULL_PTR
      IPRCON=C_NULL_PTR
      HPTRK=' '
      HPMACR=' '
      HPSYS=' '
      DO 10 I1=3,NENTRY
      LTABLE=(IENTRY(I1).EQ.1).OR.(IENTRY(I1).EQ.2)
      IF((IENTRY(I1).EQ.3).AND.(JENTRY(I1).EQ.2)) THEN
        IF(.NOT.C_ASSOCIATED(KENTRY(I1))) THEN
          CALL XABORT('FLU: NULL SEQUENTIAL-BINARY FILE HANDLE.')
          RETURN
        ENDIF
        IFTRAK=FILUNIT(KENTRY(I1))
      ELSE IF(LTABLE.AND.(JENTRY(I1).EQ.2)) THEN
        IF(.NOT.C_ASSOCIATED(KENTRY(I1))) THEN
          CALL XABORT('FLU: NULL RHS LCM HANDLE.')
          RETURN
        ENDIF
        CALL LCMLEN(KENTRY(I1),'SIGNATURE',ILONG,ITYLCM)
        IF((ILONG.NE.3).OR.(ITYLCM.NE.3)) THEN
          CALL XABORT('FLU: INVALID RHS SIGNATURE RECORD.')
          RETURN
        ENDIF
        CALL LCMGTC(KENTRY(I1),'SIGNATURE',12,HSIGN)
        IF((HSIGN.EQ.'L_TRACK').AND.(.NOT.C_ASSOCIATED(IPTRK))) THEN
          IPTRK=KENTRY(I1)
          HPTRK=HENTRY(I1)
        ELSE IF((HSIGN.EQ.'L_MACROLIB').AND.(.NOT.C_ASSOCIATED(IPMACR)))
     1  THEN
          IPMACR=KENTRY(I1)
          HPMACR=HENTRY(I1)
        ELSE IF((HSIGN.EQ.'L_LIBRARY').AND.(.NOT.C_ASSOCIATED(IPMACR)))
     1  THEN
          CALL LCMLEN(KENTRY(I1),'MACROLIB',ILONG,ITYLCM)
          IF(ILONG.NE.0) THEN
            IPMACR=LCMGID(KENTRY(I1),'MACROLIB')
            HPMACR=HENTRY(I1)
          ENDIF
        ELSE IF((HSIGN.EQ.'L_PIJ').AND.(.NOT.C_ASSOCIATED(IPSYS))) THEN
          IPSYS=KENTRY(I1)
          HPSYS=HENTRY(I1)
        ELSE IF((HSIGN.EQ.'L_FLUX').AND.(.NOT.C_ASSOCIATED(IPFLUP)))
     1  THEN
          IPFLUP=KENTRY(I1)
          HPFLUP=HENTRY(I1)
        ELSE IF((HSIGN.EQ.'L_ARCHIVE').AND.
     1  (.NOT.C_ASSOCIATED(IPARCH_BOOT))) THEN
          IPARCH_BOOT=KENTRY(I1)
        ELSE IF((HSIGN.EQ.'L_RCONTRACT').AND.
     1  (.NOT.C_ASSOCIATED(IPRCON))) THEN
          IPRCON=KENTRY(I1)
        ELSE IF((HSIGN.EQ.'L_SOURCE').AND.(.NOT.C_ASSOCIATED(IPSOU)))
     1  THEN
          IPSOU=KENTRY(I1)
          HPGPT=HENTRY(I1)
        ELSE
          WRITE(HSMG,'(20HFLU: UNKNOWN OBJECT ,A,14H OF SIGNATURE ,A,
     1    5H (1).)') TRIM(HENTRY(I1)),TRIM(HSIGN)
          CALL XABORT(HSMG)
          RETURN
        ENDIF
      ELSE
        WRITE(HSMG,'(20HFLU: UNKNOWN OBJECT ,A,1H.)') TRIM(HENTRY(I1))
        CALL XABORT(HSMG)
        RETURN
      ENDIF
   10 CONTINUE
      IF(.NOT.C_ASSOCIATED(IPTRK)) THEN
         CALL XABORT('FLU: NO TRACKING OBJECT AT RHS.')
         RETURN
      ELSE IF(.NOT.C_ASSOCIATED(IPMACR)) THEN
         CALL XABORT('FLU: NO MACROLIB OBJECT AT RHS.')
         RETURN
      ELSE IF(.NOT.C_ASSOCIATED(IPSYS)) THEN
         CALL XABORT('FLU: NO SYSTEM OBJECT AT RHS.')
         RETURN
      ENDIF
*----
*  RECOVER GENERAL TRACKING INFORMATION.
*     Publisher receives real archive/contract pointers.
      IF(.NOT.C_ASSOCIATED(IPMACR,KENTRY(3)).OR.
     1 .NOT.C_ASSOCIATED(IPTRK,KENTRY(4)).OR.
     2 .NOT.C_ASSOCIATED(IPSYS,KENTRY(5)).OR.
     3 .NOT.C_ASSOCIATED(IPARCH_BOOT,KENTRY(6)).OR.
     4 .NOT.C_ASSOCIATED(IPRCON,KENTRY(7))) CALL XABORT(
     5 "FLUGLOBAL64: COMPLETE SEVEN OPERAND ORDER REQUIRED.")
*----
      IF(.NOT.C_ASSOCIATED(IPARCH_BOOT).OR.
     1 .NOT.C_ASSOCIATED(IPRCON)) CALL XABORT(
     2 "FLUGLOBAL64: ARCH_BOOT AND RCONTRACT REQUIRED.")
      ISTATE(:NSTATE)=0
      CALL LCMLEN(IPTRK,'STATE-VECTOR',ILONG,ITYLCM)
      IF((ILONG.NE.NSTATE).OR.(ITYLCM.NE.1)) THEN
         CALL XABORT('FLU: INVALID TRACK STATE-VECTOR RECORD.')
         RETURN
      ENDIF
      CALL LCMGET(IPTRK,'STATE-VECTOR',ISTATE)
      NREG=   ISTATE(1)
      NUN=    ISTATE(2)
      LEAKSW= ISTATE(3).EQ.0
      IGP4=   ISTATE(4)
      NSOUT=  ISTATE(5)
*----
*  RECOVER MACROLIB PARAMETERS.
*----
      IF(.NOT.C_ASSOCIATED(IPARCH_BOOT).OR.
     1 .NOT.C_ASSOCIATED(IPRCON)) CALL XABORT(
     2 "FLUGLOBAL64: ARCH_BOOT AND RCONTRACT REQUIRED.")
      ISTATE(:NSTATE)=0
      CALL LCMLEN(IPMACR,'STATE-VECTOR',ILONG,ITYLCM)
      IF((ILONG.NE.NSTATE).OR.(ITYLCM.NE.1)) THEN
         CALL XABORT('FLU: INVALID MACROLIB STATE-VECTOR RECORD.')
         RETURN
      ENDIF
      CALL LCMGET(IPMACR,'STATE-VECTOR',ISTATE)
      NGRP=   ISTATE(1)
      NMAT=   ISTATE(2)
      NANIS=  ISTATE(3)-1
      NIFIS=  ISTATE(4)
      ITRANC= ISTATE(6)
      LFORW = (ISTATE(13).EQ.0)
      IF(IGP4.GT.NMAT) THEN
         WRITE(HSMG,'(45HFLU: THE NUMBER OF MIXTURES IN THE TRACKING (,
     1   I5,55H) IS GREATER THAN THE NUMBER OF MIXTURES IN THE MACROLI,
     2   3HB (,I5,2H).)') IGP4,NMAT
         CALL XABORT(HSMG)
      ENDIF
*----
*  RECOVER INFORMATION FROM L_PIJ OBJECT.
*----
      ITPIJ=2
      IPHASE=1
      ISPOD=0
      IF(C_ASSOCIATED(IPSYS)) THEN
         CALL LCMLEN(IPSYS,'LINK.MACRO',ILONG,ITYLCM)
         IF((ILONG.NE.3).OR.(ITYLCM.NE.3)) THEN
            CALL XABORT('FLU: INVALID SYSTEM LINK.MACRO RECORD.')
            RETURN
         ENDIF
         CALL LCMGTC(IPSYS,'LINK.MACRO',12,TEXT12)
         IF(HPMACR.NE.TEXT12) THEN
            WRITE(HSMG,'(37H FLU: INVALID MACROLIB OBJECT NAME ='',A12,
     1      18H'', EXPECTED NAME='',A12,2H''.)') HPMACR,TEXT12
            CALL XABORT(HSMG)
            RETURN
         ENDIF
         CALL LCMLEN(IPSYS,'LINK.TRACK',ILONG,ITYLCM)
         IF((ILONG.NE.3).OR.(ITYLCM.NE.3)) THEN
            CALL XABORT('FLU: INVALID SYSTEM LINK.TRACK RECORD.')
            RETURN
         ENDIF
         CALL LCMGTC(IPSYS,'LINK.TRACK',12,TEXT12)
         IF(HPTRK.NE.TEXT12) THEN
            WRITE(HSMG,'(37H FLU: INVALID TRACKING OBJECT NAME ='',A12,
     1      18H'', EXPECTED NAME='',A12,2H''.)') HPTRK,TEXT12
            CALL XABORT(HSMG)
            RETURN
         ENDIF
         CALL LCMLEN(IPSYS,'STATE-VECTOR',ILONG,ITYLCM)
         IF((ILONG.NE.NSTATE).OR.(ITYLCM.NE.1)) THEN
            CALL XABORT('FLU: INVALID SYSTEM STATE-VECTOR RECORD.')
            RETURN
         ENDIF
         CALL LCMGET(IPSYS,'STATE-VECTOR',ISTATE)
         ITPIJ=ISTATE(1)
         IPHASE=ISTATE(5)
         ISPOD=ISTATE(14)
         IF(ISTATE(8).NE.NGRP) CALL XABORT('FLU: INVALID NUMBER OF ENE'
     1   //'RGY GROUPS.')
         IF(ISTATE(10).GT.NMAT) CALL XABORT('FLU: INVALID NUMBER OF MI'
     1   //'XTURES.')
         IF(LEAKSW) THEN
            IF((ISTATE(2).EQ.0).OR.(ISTATE(3).EQ.0)) LEAKSW=.FALSE.
         ENDIF
      ENDIF
*----
*  INITIALISE/READ ITERATIONS PARAMETERS
*----
      IF(NREG.EQ.0) CALL XABORT('FLU: NREG = 0')
      ALLOCATE(IMERG(NMAT))
      CALL FLUGPG64(IPFLUX,IPMACR,ITYPEC,MAXOUT,MAXINR,EPSOUT,EPSUNK,
     1 EPSINR,IREBAL,IFRITR,IACITR,COPTIO,ILEAK,B2,NGRP,NREG,NMAT,
     2 NIFIS,LEAKSW,REFKEF,ITPIJ,IPRINT,REC,INITFL,NMERG,IMERG,IPICK,
     3 IMCAUD,LIMERG,IR64MD)
      LR64=IR64MD.NE.0
      IF(LR64) CALL XABORT(
     1 "FLUGLOBAL64: GLOBAL TYPE K, NOT RADIAL R64 ROUTE.")
      IF(LR64) THEN
*       The R64 path requires the sealed route-contract operand.
        IF(.NOT.C_ASSOCIATED(IPRCON)) CALL XABORT('FLU: R64 MODE '//
     1  'REQUIRES THE SEALED L_RCONTRACT OPERAND.')
        CALL SPOR64_RCONTRACT_LOAD(IPRCON,RCON,LRCON)
        IF(.NOT.LRCON) CALL XABORT('FLU: ROUTE CONTRACT '//
     1  'ADMISSION FAILED.')
*       RCONTRACT is a control operand, not one of B2B's seven physical
*       solve objects.  Keep the B2B object tuple exact and pass the
*       already loaded contract through its typed argument.
        IF(NENTRY.NE.8) CALL XABORT('FLU: R64 MODE REQUIRES SEVEN '//
     1  'SOLVE OBJECTS AND ONE ROUTE CONTRACT.')
        IF((HENTRY(8).NE.'RCONTRACT').OR.(IENTRY(8).NE.1).OR.
     1  (JENTRY(8).NE.2).OR.
     2  (.NOT.C_ASSOCIATED(KENTRY(8),IPRCON))) CALL XABORT(
     3  'FLU: R64 ROUTE CONTRACT MUST BE THE FINAL READ-ONLY LCM '//
     4  'OPERAND.')
        CALL SPOR64_B2B_INGRESS(NENTRY-1,HENTRY(1:NENTRY-1),
     1  IENTRY(1:NENTRY-1),JENTRY(1:NENTRY-1),KENTRY(1:NENTRY-1),
     2  ITYPEC,MAXOUT,MAXINR,EPSOUT,EPSUNK,EPSINR,IREBAL,IFRITR,
     3  IACITR,COPTIO,ILEAK,INITFL,NMERG,IMERG,IPRINT,REC,IMCAUD,
     4  LIMERG,NGRP,NREG,NMAT,NIFIS,ITPIJ,ITRANC,IPHASE,LEAKSW,
     5  LFORW,IR64MD,RCON,IB2STAT,CUTOFF64)
        WRITE(IOUT,5990) IR64MD,IB2STAT,CUTOFF64
        IF(IB2STAT.EQ.SPOR64_B2C_HOST_COMMITTED) THEN
          CONTINUE
        ELSE IF(IB2STAT.EQ.SPOR64_B2B_ADMISSION_FAILED) THEN
          CALL XABORT('FLU: R64 B2B READ-ONLY ADMISSION FAILED.')
        ELSE IF(IB2STAT.EQ.SPOR64_B2B_CORE_FAILED) THEN
          CALL XABORT('FLU: R64 B2B CORE FAILED.')
        ELSE IF(IB2STAT.EQ.SPOR64_B2B_NOT_ACCEPTED) THEN
          CALL XABORT('FLU: R64 B2B TERMINAL RULE NOT ACCEPTED.')
        ELSE IF(IB2STAT.EQ.SPOR64_B2B_ACCEPTED_UNPUBLISHED) THEN
          CALL XABORT('FLU: R64 B2B RESULT ACCEPTED BUT UNPUBLISHED.')
        ELSE IF(IB2STAT.EQ.SPOR64_B2C_PREFLIGHT_FAILED) THEN
          CALL XABORT('FLU: R64 B2C PUBLICATION PREFLIGHT FAILED.')
        ELSE IF(IB2STAT.EQ.SPOR64_B2C_CHILD_PUBLISHED) THEN
          CALL XABORT('FLU: R64 B2C CHILD PUBLICATION INCOMPLETE.')
        ELSE IF(IB2STAT.EQ.SPOR64_B2C_DRIVER_COMMITTED) THEN
          CALL XABORT('FLU: R64 B2C DRIVER COMMIT INCOMPLETE.')
        ELSE
          CALL XABORT('FLU: R64 B2B RETURNED AN INVALID STATUS.')
        ENDIF
        DEALLOCATE(IMERG)
        RETURN
      ENDIF
*----
*  COMMIT PARSER-INDEPENDENT LEGACY METADATA AFTER ROUTE SELECTION.
*----
      IF(.NOT.REC) THEN
        HSIGN='L_FLUX'
        CALL LCMPTC(IPFLUX,'SIGNATURE',12,HSIGN)
      ENDIF
      CALL LCMPTC(IPFLUX,'LINK.MACRO',12,HPMACR)
      IF(C_ASSOCIATED(IPSYS)) THEN
        CALL LCMPTC(IPFLUX,'LINK.TRACK',12,HPTRK)
        CALL LCMPTC(IPFLUX,'LINK.SYSTEM',12,HPSYS)
      ELSE
        CALL LCMPTC(IPFLUX,'LINK.TRACK',12,HPTRK)
      ENDIF
      IF(LIMERG) CALL LCMPUT(IPFLUX,'IMERGE-LEAK',NMAT,1,IMERG)
      IF(IPHASE.EQ.2) THEN
        IF((ILEAK.GE.7).AND.(ITPIJ.LT.3)) CALL XABORT('FLU: HETEROGE'//
     >  'NEOUS BUCKLING CALCULATIONS REQUIRE PIJK EVALUATION IN ASM:')
      ENDIF 
      IF(ITYPEC.EQ.1) THEN
        IF(.NOT.C_ASSOCIATED(IPFLUP)) CALL XABORT('FLU: NO UNPERTURBED'
     1  //'FLUX OBJECT AT RHS.')
        IF(.NOT.C_ASSOCIATED(IPSOU)) CALL XABORT('FLU: NO SOURCE OBJEC'
     1  //'T AT RHS.')
      ENDIF
*----
*  RECOVER TRACKING FILE INFORMATION.
*----
      CALL LCMGTC(IPTRK,'TRACK-TYPE',12,CMODUL)
      CALL LCMGET(IPTRK,'STATE-VECTOR',ISTATE)
      IF(IPHASE.EQ.1) THEN
        CXDOOR=CMODUL
      ELSE
        CXDOOR='TRAFIC'
        IF(.NOT.C_ASSOCIATED(IPSYS)) CALL XABORT('FLU: NO PIJ OBJECT A'
     1  //'T RHS.')
      ENDIF
      IF(CXDOOR.NE."SPOT".OR.(ITYPEC.NE.2.AND.ITYPEC.NE.3))
     1 CALL XABORT("FLUGLOBAL64: SPOT TYPE2/3 REQUIRED.")
      IF(IMCAUD.NE.0) THEN
        IF((ITYPEC.NE.0).OR.(CXDOOR.NE.'MCCG'))
     1  CALL XABORT('FLU: MOCA REQUIRES TYPE S AND MCCG.')
      ENDIF
      IF(CXDOOR.EQ.'MCCG') THEN
         NLF=ISTATE(6)
         NANI=ISTATE(6)
      ELSE IF(CXDOOR.EQ.'BIVAC')  THEN
         NLF=MAX(1,ISTATE(14))
         NANI=MAX(1,ISTATE(16))
      ELSE IF(CXDOOR.EQ.'TRIVAC') THEN
         NLF=MAX(1,ISTATE(30))
         NANI=MAX(1,ISTATE(32))
      ELSE IF(CXDOOR.EQ.'SN') THEN
         NLF=ISTATE(15)
         NANI=MAX(1,ISTATE(16))
      ELSE IF(CXDOOR.EQ.'SPOT') THEN
*        9/10 ARE THE SPATIAL ELEMENT/SCHEME, NOT ANGULAR ORDERS.
         NLF=ISTATE(15)
         NANI=MAX(1,ISTATE(16))
         NANIS=MIN(NANIS,NANI-1)
      ELSE
         NLF=1
         NANI=1
      ENDIF
*----
*  CHECK FOR THE ANISOTROPY SETTINGS COHERENCE
*----
      IF((ITRANC.NE.0).AND.(NANI.GT.1)) THEN
         WRITE(IOUT,6400) CXDOOR,NANI
         ITRANC=0
      ENDIF
*----
*  RECOVER TABULATED FUNCTIONS FOR THE METHOD OF CHARACTERISTICS.
*----
      IF(CXDOOR.EQ.'MCCG') CALL XDRTA2
*----
*  THE NUMBER OF UNKNOWNS OF A CURRENT-BASED SYBIL ITERATION IS
*  INCREASED TO HOLD INTERFACE CURRENT COMPONENTS.
*----
      IF(CXDOOR.EQ.'SYBIL') NUN=NUN+ISTATE(9)
*----
*  THE NUMBER OF UNKNOWNS IS MULTIPLIED BY 2 WITH THE ECCO-TYPE
*  ISOTROPIC STREAMING MODEL AND BY 4 FOR PIJ AND 8 FOR MOC WITH THE
*  TIBERE ANISOTROPIC STREAMING MODEL. THE EXTRA-LOCATIONS ARE USED TO
*  STORE THE HETEROGENEOUS FUNDAMENTAL CURRENT VALUES.
*----
      IF(ILEAK.EQ.6) NUN=NUN*2
      IF(ILEAK.GE.7) THEN
        IF (CXDOOR.EQ.'MCCG')THEN
          NUN=NUN*8
        ELSE
          NUN=NUN*4
        ENDIF
      ENDIF  
*----
*  PRINT REQUIRED INFORMATION
*----
      IF(IPRINT.GE.1) THEN
        IF(LFORW) THEN
          TYPE10='    DIRECT'
        ELSE
          TYPE10='   ADJOINT'
        ENDIF
        IF(NLF.EQ.1 ) THEN
          HISO10=' ISOTROPIC'
        ELSE
          HISO10=' ANISOTROP'
        ENDIF
        WRITE(IOUT,6010) HTYPE(ITYPEC),TYPE10,HISO10
        IF(ITYPEC.EQ.3) THEN
            WRITE(IOUT,6011) COPTIO,CLEAK(MOD(ILEAK,10)),' IMPOSED'
            IF(ILEAK.LT.7) THEN
              WRITE(IOUT,6012) B2(4)
            ELSE
              WRITE(IOUT,6013) B2(1),B2(2),B2(3)
            ENDIF
        ELSE IF(ITYPEC.GT.3) THEN
          IF(ILEAK.LT.7) THEN
            WRITE(IOUT,6011) COPTIO,CLEAK(ILEAK),'G SEARCH'
            WRITE(IOUT,6012) B2(4)
          ELSE
            WRITE(IOUT,6011) COPTIO,CLEAK(7),CSDIR(ILEAK/10)//' SEARCH'
            WRITE(IOUT,6013) B2(1),B2(2),B2(3)
          ENDIF
        ENDIF
        CREBAL='ON '
        IF(IREBAL.EQ.0) CREBAL='OFF'
        CHLEAK='ON '
        IF(LEAKSW) CHLEAK='OFF'
        WRITE(IOUT,6000) CXDOOR,NGRP,NREG,NUN,NMERG,MAXOUT,MAXINR,
     >                   IFRITR,IACITR,CREBAL,REDUC(ITPIJ),CHLEAK,
     >                   EPSOUT,EPSUNK,EPSINR
        IF(ITRANC.GT.0) WRITE(IOUT,6100)
      ENDIF
*----
*  RECOVER SPECIFIC TRACKING INFORMATION.
*----
      IF(CXDOOR.EQ.'MCCG') THEN
         CALL LCMLEN(IPTRK,'MCCG-STATE',ILONG,ITYLCM)
         IF((ILONG.NE.NSTATE).OR.(ITYLCM.NE.1)) THEN
            CALL XABORT('FLU: INVALID MCCG-STATE RECORD.')
            RETURN
         ENDIF
         CALL LCMGET(IPTRK,'MCCG-STATE',ISTATE)
         NFUNL=ISTATE(19)
         NLIN=ISTATE(20)
      ELSE IF(CXDOOR.EQ.'SN') THEN
         CALL LCMGET(IPTRK,'STATE-VECTOR',ISTATE)
         NFUNL=ISTATE(7)
         NLIN=ISTATE(8)
         NDIM=ISTATE(9)
         NLIN=NLIN**NDIM
         NLIN=NLIN*ISTATE(35)
      ELSE IF(CXDOOR.EQ.'SPOT') THEN
         CALL LCMGET(IPTRK,'STATE-VECTOR',ISTATE)
         NFUNL=ISTATE(16)
         NLIN=ISTATE(9)
      ELSE
         NFUNL=1
         NLIN=1
      ENDIF
      ALLOCATE(MATCOD(NREG),VOL(NREG),KEYFLX(NREG,NLIN,NFUNL))
      KEYFLX(:NREG,:NLIN,:NFUNL)=0
      CALL LCMLEN(IPTRK,'MATCOD',ILNLCM,ITYLCM)
      IF((ILNLCM.NE.NREG).OR.(ITYLCM.NE.1))
     1   CALL XABORT( 'FLU: INCOMPATIBLE NUMBER OF REGIONS.')
      CALL LCMGET(IPTRK,'MATCOD',MATCOD)
      CALL LCMLEN(IPTRK,'VOLUME',ILNLCM,ITYLCM)
      IF((ILNLCM.NE.NREG).OR.(ITYLCM.NE.2))
     1   CALL XABORT('FLU: INVALID VOLUME RECORD.')
      CALL LCMGET(IPTRK,'VOLUME',VOL)
      IF((CXDOOR.EQ.'MCCG').OR.(CXDOOR.EQ.'SN').OR.
     1 (CXDOOR.EQ.'SPOT')) THEN
         CALL LCMLEN(IPTRK,'KEYFLX$ANIS',ILNLCM,ITYLCM)
         IF((ILNLCM.NE.NREG*NLIN*NFUNL).OR.(ITYLCM.NE.1))
     1      CALL XABORT('FLU: INVALID KEYFLX$ANIS RECORD.')
         CALL LCMGET(IPTRK,'KEYFLX$ANIS',KEYFLX)
      ELSE
         CALL LCMLEN(IPTRK,'KEYFLX',ILNLCM,ITYLCM)
         IF((ILNLCM.NE.NREG*NLIN*NFUNL).OR.(ITYLCM.NE.1))
     1      CALL XABORT('FLU: INVALID KEYFLX RECORD.')
         CALL LCMGET(IPTRK,'KEYFLX',KEYFLX)
      ENDIF
      CALL LCMLEN(IPTRK,'TITLE',ILNLCM,ITYLCM)
      IF( ILNLCM.GT.0 )THEN
         IF((ILNLCM.NE.18).OR.(ITYLCM.NE.3))
     1      CALL XABORT('FLU: INVALID TITLE RECORD.')
         CALL LCMGTC(IPTRK,'TITLE',72,TITLE)
      ELSE
         TITLE='*** NO TITLE PROVIDED ***'
      ENDIF
*----
*  COMPUTE THE FLUX.
*----
      IF(ITYPEC.EQ.1) THEN
*       FIXED SOURCE EIGENVALUE PROBLEM
        CALL FLUGPT(IPRINT,IPFLUX,IPTRK,IPMACR,IPFLUP,IPSOU,IFTRAK,
     1  IPSYS,IPHASE,ITPIJ,CXDOOR,TITLE,INITFL,LFORW,LEAKSW,IREBAL,
     2  NGRP,NMAT,NIFIS,NANIS,NLF,NLIN,NFUNL,COPTIO,NUN,MAXINR,EPSINR,
     3  MAXOUT,EPSUNK,EPSOUT,IFRITR,IACITR,ILEAK,NREG,NSOUT,MATCOD,
     4  KEYFLX,VOL,REFKEF,NMERG,IMERG)
      ELSE
        CALL FLUDRVG64(IPRINT,IPFLUX,IPTRK,IPMACR,IPSOU,IFTRAK,IPSYS,
     1  IPHASE,ITPIJ,CXDOOR,ITRANC,TITLE,B2,INITFL,LFORW,LEAKSW,IREBAL,
     2  NGRP,NMAT,NIFIS,NANIS,NLF,NLIN,NFUNL,COPTIO,NUN,MAXINR,EPSINR,
     3  MAXOUT,EPSUNK,EPSOUT,IFRITR,IACITR,ITYPEC,ILEAK,NREG,NSOUT,
     4  MATCOD,KEYFLX,VOL,REFKEF,NMERG,IMERG,IMCAUD,LR64,REC,
     5  TERMINAL_FLUX64,TERMINAL_SOURCE64,TERMINAL_KEFF64,
     6  TERMINAL_RESID64,TERMINAL_COUNTERS,TERMINAL_INNER_STATE,
     7  TERMINAL_VALID)
      ENDIF
*----
*  VERIFY THE MODAL SPOD SYSTEM TAG.
*----
      IF((CXDOOR.EQ.'SPOT').AND.(ISPOD.NE.1))
     1 CALL XABORT('FLU: MISSING SPOD INFORMATION.')
*----
*  PRESERVE THE LEAK1D USED BY A RADIAL SPOT SOLVE IN ITS FLUX OBJECT.
*----
      IF(C_ASSOCIATED(IPSYS)) THEN
        CALL LCMLEN(IPSYS,'SPOT-L1-RAW',ILONG,ITYLCM)
        IF(ILONG.NE.0) CALL XABORT('FLU: UNREDUCED SYSTEM REQUIRES '
     1  //'THE REAL64 DOOR.')
        CALL LCMLEN(IPSYS,'SPOT-LEAK1D',ILONG,ITYLCM)
        IF(ILONG.EQ.NGRP) THEN
          ALLOCATE(LEAK1D(NGRP))
          CALL LCMGET(IPSYS,'SPOT-LEAK1D',LEAK1D)
          CALL LCMPUT(IPFLUX,'SPOT-LEAK1D',NGRP,2,LEAK1D)
          DEALLOCATE(LEAK1D)
        ELSE IF(ILONG.NE.0) THEN
          CALL XABORT('FLU: INVALID SYSTEM SPOT-LEAK1D LENGTH.')
        ENDIF
      ENDIF
*----
*  RELEASE GENERAL TRACKING INFORMATION.
*----
      IF(.NOT.TERMINAL_VALID) CALL XABORT(
     1 "FLUGLOBAL64: NO ACTUAL STRICT GLOBAL TERMINAL.")
      CALL SPOR64_BOOT_CANONICAL64_WRITE(IPFLUX,IPTRK,IPSYS,
     1 IPMACR,CANONICAL_OK)
      IF(.NOT.CANONICAL_OK) CALL XABORT(
     1 "FLUGLOBAL64: ACTUAL CANONICAL WRITE FAILED.")
      CALL SPOR64_BOOT_GLOBAL_PUBLISH(IPGLOBAL,IPFLUX,IPTRK,
     1 IPSYS,IPMACR,IPARCH_BOOT,IPRCON,TERMINAL_FLUX64,
     2 TERMINAL_SOURCE64,TERMINAL_KEFF64,TERMINAL_RESID64,
     3 TERMINAL_COUNTERS,TERMINAL_INNER_STATE,TERMINAL_VALID,
     4 IGLOBAL_STAT)
      IF(IGLOBAL_STAT.NE.SPOR64_BOOT_GLOBAL_PUBLISHED)
     1 CALL XABORT("FLUGLOBAL64: GLOBAL PUBLICATION FAILED.")
      DEALLOCATE(TERMINAL_FLUX64,TERMINAL_SOURCE64)
      DEALLOCATE(IMERG)
      DEALLOCATE(KEYFLX,VOL,MATCOD)
      RETURN
*
5990  FORMAT(' SPOR64 R64 MODE=',I2,' STATUS=',I2,
     1 ' ACA-CUTOFF-LOCAL-PREDICATE-DIFFERENCES=',I20)
6000  FORMAT(' FLUX SOLUTION DOOR          = ** ',A6,' **'/
     > ' NB. OF GROUPS               =',I10/
     > ' NB. OF REGIONS              =',I10/
     > ' NB. OF UNKNOWNS PER GROUP   =',I10/
     > ' NB. OF LEAKAGE ZONES        =',I10/
     > ' MAX. OUTER ITERATIONS       =',I10/
     > ' MAX. THERMAL ITERATIONS     =',I10/
